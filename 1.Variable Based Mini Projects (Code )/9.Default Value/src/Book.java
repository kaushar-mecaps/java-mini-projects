public class Book {

    /**
     * This class represents a book with various attributes such as
     * title, price, author, rating, bestseller status, and ID.
     * It serves as a blueprint for creating book objects in the application.
     */
    // Title of the book
    String title;
    // Price of the book
    double price;
    // Name of the author of the book
    String author;
    // Average rating of the book
    float rating;
    // Indicates whether the book is a bestseller
    boolean isBestSeller;
    // Unique identifier for the book
    int id;


}
